UPDATE product
SET del_flag = 1, update_time = NOW()
WHERE shop_id = @shop_id
  AND del_flag = 0
  AND name IN ('抽取式厨房纸巾 3 层', '无图商品测试');

UPDATE product_sku s
JOIN product p ON p.id = s.product_id
SET s.del_flag = 1, s.update_time = NOW()
WHERE p.del_flag = 1 AND s.del_flag = 0;

